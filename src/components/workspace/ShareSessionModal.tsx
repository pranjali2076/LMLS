'use client';

import React, { useState, useMemo } from 'react';
import { useApp } from '@/context/AppContext';
import {
  Share2,
  Copy,
  Check,
  X,
  Link as LinkIcon,
  FileText,
  ShieldCheck,
  Sparkles,
  ExternalLink,
} from 'lucide-react';

export default function ShareSessionModal() {
  const {
    isShareModalOpen,
    setIsShareModalOpen,
    shareModalData,
    activeModel,
  } = useApp();

  const [copiedLink, setCopiedLink] = useState(false);
  const [copiedTranscript, setCopiedTranscript] = useState(false);

  // Generate shareable base64 query param
  const shareUrl = useMemo(() => {
    if (typeof window === 'undefined') return '';
    try {
      const payload = {
        title: shareModalData?.title || 'LMLS Investigation Session',
        messages: shareModalData?.messages || [],
        createdAt: shareModalData?.createdAt || new Date().toLocaleDateString(),
        model: shareModalData?.model || activeModel,
      };
      const jsonStr = JSON.stringify(payload);
      const encoded = btoa(unescape(encodeURIComponent(jsonStr)));
      const origin = window.location.origin;
      return `${origin}/app?shared=${encoded}`;
    } catch {
      return window.location.href;
    }
  }, [shareModalData, activeModel]);

  const fullMarkdown = useMemo(() => {
    if (!shareModalData) return '';
    if (shareModalData.transcript) {
      return `# ${shareModalData.title}\n*Generated by LMLS Cognitive Architecture (${shareModalData.model}) — ${shareModalData.createdAt}*\n\n---\n\n${shareModalData.transcript}`;
    }
    const lines = (shareModalData.messages || []).map(
      (m) => `### [${m.role.toUpperCase()}] (${m.timestamp})\n\n${m.content}`
    );
    return `# ${shareModalData.title}\n*Generated by LMLS Cognitive Architecture (${shareModalData.model})*\n\n---\n\n${lines.join('\n\n---\n\n')}`;
  }, [shareModalData]);

  if (!isShareModalOpen) return null;

  const handleCopyLink = () => {
    if (!shareUrl) return;
    navigator.clipboard.writeText(shareUrl);
    setCopiedLink(true);
    setTimeout(() => setCopiedLink(false), 2500);
  };

  const handleCopyTranscript = () => {
    if (!fullMarkdown) return;
    navigator.clipboard.writeText(fullMarkdown);
    setCopiedTranscript(true);
    setTimeout(() => setCopiedTranscript(false), 2500);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-md animate-in fade-in duration-200">
      <div className="w-full max-w-lg rounded-3xl bg-[#0b1320]/95 backdrop-blur-2xl border border-emerald-500/30 shadow-2xl p-6 text-slate-100 space-y-5 animate-in zoom-in-95 duration-150">
        {/* Header */}
        <div className="flex items-center justify-between pb-3 border-b border-white/10">
          <div className="flex items-center gap-2.5">
            <div className="w-9 h-9 rounded-xl bg-gradient-to-tr from-emerald-500 to-teal-500 flex items-center justify-center text-slate-950 shadow-md shadow-emerald-500/25">
              <Share2 className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-base font-bold text-white flex items-center gap-2">
                Share Session
                <span className="text-[10px] font-mono px-2 py-0.5 rounded-full bg-emerald-500/20 text-emerald-300 border border-emerald-500/30">
                  Read-Only Link
                </span>
              </h2>
              <p className="text-xs text-slate-400">
                Create a public read-only link or copy full Markdown transcript
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={() => setIsShareModalOpen(false)}
            className="p-1.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800/60 transition-colors"
            title="Close"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Session Card Snapshot */}
        <div className="p-3.5 rounded-2xl bg-slate-950/70 border border-white/10 space-y-1.5">
          <div className="text-xs font-semibold text-emerald-300 flex items-center gap-1.5">
            <Sparkles className="w-3.5 h-3.5 text-emerald-400" />
            <span>{shareModalData?.title || 'LMLS Investigation Session'}</span>
          </div>
          <div className="text-[11px] text-slate-400 flex items-center gap-3 font-mono">
            <span>Model: {shareModalData?.model || activeModel}</span>
            <span>•</span>
            <span>{shareModalData?.messages?.length || 0} messages</span>
            <span>•</span>
            <span>{shareModalData?.createdAt || 'Today'}</span>
          </div>
        </div>

        {/* 1. Shareable Read-Only URL Box */}
        <div className="space-y-1.5">
          <label className="block text-xs font-semibold uppercase tracking-wider text-slate-300">
            Shareable Read-Only URL
          </label>
          <div className="flex items-center gap-2">
            <div className="flex-1 flex items-center gap-2 px-3.5 py-2.5 rounded-xl bg-slate-900/90 border border-white/10 text-xs font-mono text-slate-300 truncate">
              <LinkIcon className="w-3.5 h-3.5 text-emerald-400 shrink-0" />
              <span className="truncate">{shareUrl}</span>
            </div>
            <button
              type="button"
              id="copy-share-link-btn"
              onClick={handleCopyLink}
              className={`px-3.5 py-2.5 rounded-xl text-xs font-semibold flex items-center gap-1.5 transition-all shrink-0 cursor-pointer ${
                copiedLink
                  ? 'bg-emerald-500 text-slate-950'
                  : 'bg-emerald-500/20 hover:bg-emerald-500/30 text-emerald-300 border border-emerald-500/40'
              }`}
            >
              {copiedLink ? (
                <>
                  <Check className="w-3.5 h-3.5" />
                  <span>Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Link</span>
                </>
              )}
            </button>
          </div>
          <p className="text-[11px] text-slate-400 leading-relaxed">
            Anyone with this link can view this study session in read-only mode and fork it into their own workspace.
          </p>
        </div>

        {/* 2. Markdown Transcript Option */}
        <div className="space-y-1.5 pt-1">
          <label className="block text-xs font-semibold uppercase tracking-wider text-slate-300">
            Export Transcript for Discord / WhatsApp / GitHub
          </label>
          <div className="flex items-center justify-between p-3 rounded-2xl bg-slate-950/60 border border-white/5">
            <div className="flex items-center gap-2.5">
              <div className="p-2 rounded-xl bg-teal-500/20 text-teal-300">
                <FileText className="w-4 h-4" />
              </div>
              <div>
                <div className="text-xs font-medium text-white">Full Markdown Transcript (.md)</div>
                <div className="text-[10px] text-slate-400">Includes all prompts, code blocks, and AI replies</div>
              </div>
            </div>
            <button
              type="button"
              id="copy-md-transcript-btn"
              onClick={handleCopyTranscript}
              className={`px-3 py-1.5 rounded-xl text-xs font-semibold flex items-center gap-1.5 transition-all cursor-pointer ${
                copiedTranscript
                  ? 'bg-teal-500 text-slate-950'
                  : 'bg-slate-800 hover:bg-slate-700 text-slate-200 border border-white/10'
              }`}
            >
              {copiedTranscript ? (
                <>
                  <Check className="w-3.5 h-3.5" />
                  <span>Copied .md</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy (.md)</span>
                </>
              )}
            </button>
          </div>
        </div>

        {/* Security / Privacy notice */}
        <div className="p-3 rounded-xl bg-emerald-950/30 border border-emerald-500/20 flex items-start gap-2.5 text-xs text-emerald-200/90">
          <ShieldCheck className="w-4 h-4 text-emerald-400 shrink-0 mt-0.5" />
          <p className="text-[11px] leading-relaxed">
            Shared sessions contain only message text and metadata. Personal credentials, API keys, and account tokens are never exposed.
          </p>
        </div>
      </div>
    </div>
  );
}
